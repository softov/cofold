/**
 * Writes each creature's reference drawing to `src/creatures/<name>/reference.svg`:
 * the body filled, the detail in ink, and two black eyes. Run `npm run references`
 * after changing a creature; the files are generated, so edit the creature instead.
 */

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { BOOD_BODIES, referenceScene, sceneSvg } from "../dist/index.js";

const root = fileURLToPath(new URL("../src/creatures/", import.meta.url));

for (const body of BOOD_BODIES) {
  const svg = sceneSvg(referenceScene(body), {
    width: 850,
    title: `bood ${body}`,
  });
  const file = `${root}${body}/reference.svg`;
  writeFileSync(
    file,
    `<!-- Generated by scripts/references.mjs from index.ts. Do not edit. Recolour the body with the CSS variable bood-color. -->\n${svg}\n`,
  );
  console.log(`wrote src/creatures/${body}/reference.svg`);
}
